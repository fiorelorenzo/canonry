// Turns `playbooks/*.md` into a TypeScript module, so a built playbook is a string in the bundle
// rather than a file somebody has to remember to ship.
//
// The previous approach resolved `new URL('../playbooks/', import.meta.url)` at runtime. That is
// correct from `src/` under vitest and from `dist/` under tsc, and wrong the moment the app is
// bundled: SvelteKit rewrites the module into `build/server/chunks/`, so the lookup went hunting
// for `build/server/chunks/playbooks/obsidian.md`, which nothing had copied there either. Every
// import on production failed with ENOENT until the first document was read.
//
// The markdown files stay the source of truth and stay editable; this only decides how they reach
// the running process. Run from `packages/import` as part of `build`, `check` and `test`, so the
// generated file cannot drift from the directory it is generated from.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const playbooksDir = path.join(here, '..', 'playbooks');
const outFile = path.join(here, '..', 'src', 'playbooks.generated.ts');

const names = (await readdir(playbooksDir)).filter((n) => n.endsWith('.md')).sort();
if (names.length === 0) throw new Error(`no playbooks found in ${playbooksDir}`);

const entries = await Promise.all(
	names.map(async (name) => {
		const source = await readFile(path.join(playbooksDir, name), 'utf8');
		const id = name.slice(0, -3);
		// A template literal keeps the markdown readable in the generated file, so a diff on it is
		// legible. Only backticks, `${` and backslashes need escaping.
		const escaped = source.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
		return `\t${JSON.stringify(id)}: \`${escaped}\``;
	})
);

const banner = `// Generated by scripts/generate-playbooks.mjs from packages/import/playbooks/*.md.
// Do not edit: edit the markdown and re-run \`pnpm --filter @canonry/import build\`.
//
// These are strings rather than files on purpose: a runtime path relative to this module breaks
// under any bundler, which is how every production import failed with ENOENT.

/** Every built-in playbook, by id, exactly as written in \`playbooks/<id>.md\`. */
export const BUILTIN_PLAYBOOK_SOURCES: Readonly<Record<string, string>> = {
${entries.join(',\n')}
};

/** The ids that exist, in a stable order, for anything that lists them. */
export const BUILTIN_PLAYBOOK_IDS = Object.keys(BUILTIN_PLAYBOOK_SOURCES);
`;

await writeFile(outFile, banner, 'utf8');
console.log(`generated ${path.relative(process.cwd(), outFile)} from ${names.length} playbooks`);
